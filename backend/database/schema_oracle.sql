CREATE OR REPLACE TRIGGER trg_update_driver_rating
AFTER INSERT ON ratings
FOR EACH ROW
DECLARE
    v_driver_id NUMBER;
    v_avg_rating NUMBER(3, 2);
BEGIN
    BEGIN
        SELECT id INTO v_driver_id FROM drivers WHERE user_id = :NEW.rated_user_id;
    EXCEPTION WHEN NO_DATA_FOUND THEN v_driver_id := NULL; END;
    
    IF v_driver_id IS NOT NULL THEN
        SELECT ROUND(AVG(score), 2) INTO v_avg_rating FROM ratings 
        WHERE rated_user_id = :NEW.rated_user_id AND rated_by = 'Rider';
        UPDATE drivers SET average_rating = COALESCE(v_avg_rating, 0) WHERE id = v_driver_id;
        IF v_avg_rating < 3.5 THEN
            UPDATE drivers SET is_flagged = 1, flagged_reason = 'Low average rating' WHERE id = v_driver_id;
        END IF;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_archive_ride
AFTER UPDATE ON rides
FOR EACH ROW
BEGIN
    IF :NEW.status = 'Completed' AND :OLD.status != 'Completed' THEN
        INSERT INTO ride_history (ride_id, rider_id, driver_id, vehicle_id, pickup_location_id, dropoff_location_id, ride_status, fare, distance_km, duration_minutes)
        VALUES (:NEW.id, :NEW.rider_id, :NEW.driver_id, :NEW.vehicle_id, :NEW.pickup_location_id, :NEW.dropoff_location_id, 'Completed', COALESCE(:NEW.final_fare, :NEW.final_amount), COALESCE(:NEW.distance_km, :NEW.actual_distance), :NEW.duration_minutes);
    ELSIF :NEW.status = 'Cancelled' AND :OLD.status != 'Cancelled' THEN
        INSERT INTO ride_history (ride_id, rider_id, driver_id, vehicle_id, pickup_location_id, dropoff_location_id, ride_status, fare, distance_km, duration_minutes)
        VALUES (:NEW.id, :NEW.rider_id, :NEW.driver_id, :NEW.vehicle_id, :NEW.pickup_location_id, :NEW.dropoff_location_id, 'Cancelled', COALESCE(:NEW.final_fare, :NEW.final_amount), COALESCE(:NEW.distance_km, :NEW.actual_distance), :NEW.duration_minutes);
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_update_driver_stats
AFTER UPDATE ON rides
FOR EACH ROW
BEGIN
    IF :NEW.status = 'Completed' AND :OLD.status != 'Completed' THEN
        UPDATE drivers SET total_trips_completed = total_trips_completed + 1, availability_status = 'Online' WHERE id = :NEW.driver_id;
    ELSIF :NEW.status = 'Cancelled' AND :OLD.status != 'Cancelled' AND :NEW.cancelled_by = 'Driver' THEN
        UPDATE drivers SET availability_status = 'Online' WHERE id = :NEW.driver_id;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_set_driver_on_trip
AFTER UPDATE ON rides
FOR EACH ROW
BEGIN
    IF :NEW.status IN ('Accepted', 'Driver En Route', 'In Progress') AND :OLD.status = 'Requested' THEN
        UPDATE drivers SET availability_status = 'On Trip' WHERE id = :NEW.driver_id;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_create_driver_earning
AFTER UPDATE ON rides
FOR EACH ROW
DECLARE v_commission_pct NUMBER(5,2) := 20.00;
BEGIN
    IF :NEW.status = 'Completed' AND :OLD.status != 'Completed' THEN
        INSERT INTO driver_earnings (driver_id, ride_id, gross_fare, commission_percent, commission_amount, net_earning)
        VALUES (:NEW.driver_id, :NEW.id, COALESCE(:NEW.final_fare, :NEW.final_amount), v_commission_pct, ROUND(COALESCE(:NEW.final_fare, :NEW.final_amount) * v_commission_pct / 100, 2), ROUND(COALESCE(:NEW.final_fare, :NEW.final_amount) * (100 - v_commission_pct) / 100, 2));
    END IF;
END;
/

