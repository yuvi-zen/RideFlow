CREATE OR REPLACE PROCEDURE calculate_fare(
    p_vehicle_type IN VARCHAR2, p_distance_km IN NUMBER, p_duration_minutes IN NUMBER, p_surge_multiplier IN NUMBER,
    p_base_fare OUT NUMBER, p_per_km_charge OUT NUMBER, p_duration_charge OUT NUMBER, p_subtotal OUT NUMBER, p_final_fare OUT NUMBER
) AS
    v_base_rate NUMBER(10, 2); v_per_km_rate NUMBER(8, 2); v_per_minute_rate NUMBER(8, 2);
BEGIN
    SELECT base_rate, per_km_rate, per_minute_rate INTO v_base_rate, v_per_km_rate, v_per_minute_rate FROM fare_rules WHERE vehicle_type = p_vehicle_type;
    p_base_fare := v_base_rate; p_per_km_charge := (p_distance_km * v_per_km_rate); p_duration_charge := (p_duration_minutes * v_per_minute_rate);
    p_subtotal := (p_base_fare + p_per_km_charge + p_duration_charge);
    p_final_fare := ROUND(p_subtotal * COALESCE(p_surge_multiplier, 1.0), 2);
END;
/

CREATE OR REPLACE PROCEDURE get_available_drivers(
    p_latitude IN NUMBER, p_longitude IN NUMBER, p_max_distance_km IN NUMBER, p_vehicle_type IN VARCHAR2, p_cursor OUT SYS_REFCURSOR
) AS v_pi NUMBER := 3.141592653589793;
BEGIN
    OPEN p_cursor FOR
    SELECT d.id, u.full_name, u.email, d.average_rating, d.current_location_lat, d.current_location_lng,
        (6371 * ACOS(COS(p_latitude * v_pi / 180) * COS(d.current_location_lat * v_pi / 180) * COS((d.current_location_lng * v_pi / 180) - (p_longitude * v_pi / 180)) + SIN(p_latitude * v_pi / 180) * SIN(d.current_location_lat * v_pi / 180))) AS distance_km
    FROM drivers d JOIN users u ON d.user_id = u.id JOIN vehicles v ON d.id = v.driver_id
    WHERE d.availability_status = 'Online' AND d.verification_status = 'Verified' AND v.verification_status = 'Verified' AND v.vehicle_type = p_vehicle_type AND d.is_flagged = 0
    AND (6371 * ACOS(COS(p_latitude * v_pi / 180) * COS(d.current_location_lat * v_pi / 180) * COS((d.current_location_lng * v_pi / 180) - (p_longitude * v_pi / 180)) + SIN(p_latitude * v_pi / 180) * SIN(d.current_location_lat * v_pi / 180))) <= p_max_distance_km
    ORDER BY d.average_rating DESC, distance_km ASC FETCH FIRST 10 ROWS ONLY;
END;
/

CREATE OR REPLACE PROCEDURE get_rider_wallet_balance(p_rider_id IN NUMBER, p_balance OUT NUMBER) AS
BEGIN
    SELECT COALESCE(SUM(CASE WHEN type IN ('TopUp', 'Refund', 'PromoCredit') THEN amount WHEN type IN ('RidePayment', 'Withdrawal') THEN -amount END), 0) INTO p_balance
    FROM wallet_transactions WHERE rider_id = p_rider_id;
END;
/

CREATE OR REPLACE PROCEDURE get_admin_platform_overview(p_total_users OUT NUMBER, p_total_drivers OUT NUMBER, p_total_rides OUT NUMBER, p_total_revenue OUT NUMBER, p_active_complaints OUT NUMBER) AS
BEGIN
    SELECT COUNT(*) INTO p_total_users FROM users;
    SELECT COUNT(*) INTO p_total_drivers FROM drivers;
    SELECT COUNT(*) INTO p_total_rides FROM rides;
    SELECT COALESCE(SUM(COALESCE(final_fare, final_amount)), 0) INTO p_total_revenue FROM rides WHERE status = 'Completed';
    SELECT COUNT(*) INTO p_active_complaints FROM complaints WHERE status IN ('Open', 'In Review');
END;
